// Generate comprehensive keyword strings for different pages
export const generateThaiKeywords = (
  pageType: 'home' | 'baskets' | 'custom' | 'product' | 'contact' | 'about'
) => {
  const {
    coreGifts,
    baskets,
    custom,
    premium,
    regions,
    services,
    occasions,
    business,
    categories,
  } = thaiKeywords;

  const baseKeywords = [
    ...coreGifts,
    ...baskets,
    ...premium,
    'giftoryth',
    'gift baskets',
    'premium baskets',
    'custom gifts',
  ];

  switch (pageType) {
    case 'home':
      return [
        ...baseKeywords,
        ...regions.slice(0, 10), // Top 10 cities
        ...services,
        ...occasions.slice(0, 5), // Top 5 occasions
      ].join(', ');

    case 'baskets':
      return [
        ...baskets,
        ...coreGifts,
        ...categories,
        ...premium,
        'ตะกร้าของขวัญ',
        'ตะกร้าของฝาก',
        'กระเช้าแฮม',
        'กระเช้าผลไม้',
      ].join(', ');

    case 'custom':
      return [
        ...custom,
        ...baskets,
        ...coreGifts,
        ...business,
        'ของขวัญสั่งทำ',
        'ของฝากสั่งทำ',
        'ออกแบบของขวัญ',
        'ออกแบบของฝาก',
      ].join(', ');

    case 'product':
      return [
        ...baskets,
        ...coreGifts,
        ...categories,
        ...premium,
        'ของขวัญพรีเมียม',
        'ของฝากพรีเมียม',
      ].join(', ');

    case 'contact':
      return [
        ...baseKeywords,
        ...services,
        ...regions.slice(0, 5), // Top 5 cities
        'ติดต่อ',
        'สอบถาม',
        'ปรึกษา',
        'บริการลูกค้า',
      ].join(', ');

    case 'about':
      return [
        ...baseKeywords,
        ...business,
        'เกี่ยวกับเรา',
        'ประวัติ',
        'ทีมงาน',
        'ความเชี่ยวชาญ',
      ].join(', ');

    default:
      return baseKeywords.join(', ');
  }
};

